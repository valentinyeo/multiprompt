export function paletteIds(text) {
  return [...new Set([...text.matchAll(/(?:g_search_results\[[^\]]+\]\s*=\s*|\.target\s*=\s*)(?:app_state\.)?(SEARCH_[A-Z0-9_]+)/g)].map(match => match[1]))].sort();
}

export function coverage(text) {
  const ids = paletteIds(text);
  return {
    ids,
    missing: ids.filter(id => !verbs[id] && !screen[id]),
    both: ids.filter(id => verbs[id] && screen[id])
  };
}
