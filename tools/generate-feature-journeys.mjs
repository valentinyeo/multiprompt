import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { inventory, featureDirectory } from './check-feature-coverage.mjs';
import { parseShortcutRows } from './shortcuts-doc.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skill = '.claude/skills/verify-multiprompt';
const manifest = `${skill}/generated-journeys.json`;
const slug = text => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const colors = {
  SEARCH_THEME_DARK_OFFSET: ['dark', 16],
  SEARCH_THEME_MID_OFFSET: ['mid', 60],
  SEARCH_THEME_LIGHT_OFFSET: ['light', 243],
  SEARCH_THEME_AMOLED_OFFSET: ['amoled', 0],
  SEARCH_THEME_EDGE_GRAY_OFFSET: ['edgegray', 51],
};

export function generate(read) {
  const entries = inventory(read);
  const palette = read('src/command_palette.zig');
  const themeBand = palette.match(/const theme_ids = \[_\]usize\{([^}]+)\};/);
  if (!themeBand) throw new Error('Cannot find the palette theme band');
  const labels = new Map([...palette.matchAll(/\b(SEARCH_THEME_\w+_OFFSET) => "([^"]+)",/g)].map(([, id, label]) => [id, label]));
  const rows = [];
  for (const symbol of themeBand[1].match(/SEARCH_\w+/g)) {
    const policy = colors[symbol];
    if (!policy) continue;
    const query = labels.get(symbol);
    if (!query) throw new Error(`No palette label for ${symbol}`);
    rows.push({ feature: `generated-theme-${policy[0]}`, id: `palette:${symbol}`, shape: 'theme-color', title: `Theme ${query}`, query, saved: policy[0], rgb: policy[1] });
  }
  let section = '';
  for (const row of parseShortcutRows(read('src/shortcuts.zig'))) {
    if (row.header) { section = slug(row.a); continue; }
    if (section !== 'view' || row.a !== 'Ctrl+Shift+B') continue;
    rows.push({ feature: 'generated-sidebar-cycle', id: `shortcut:${section}/${slug(row.a)}`, shape: 'sidebar-cycle', title: row.b, keys: [0x11, 0x10, 0x42], chord: row.a });
  }
  if (entries.some(entry => entry.id === 'palette:SEARCH_HIDESIDEBAR_OFFSET')) {
    rows.push({ feature: 'generated-sidebar-expand', id: 'palette:SEARCH_HIDESIDEBAR_OFFSET', shape: 'sidebar-expand', title: 'Expand sidebar', command: 'Sidebar: expand' });
  }
  const ids = new Set(entries.map(entry => entry.id));
  for (const row of rows) if (!ids.has(row.id)) throw new Error(`Generated row has no source entry: ${row.id}`);
  const covered = new Set(rows.map(row => row.id));
  const gaps = entries.filter(entry => !covered.has(entry.id)).map(entry => ({ ...entry, reason: 'Needs a bespoke assertion or prerequisite; no generated live claim.' }));
  return { rows: rows.sort((a, b) => a.feature.localeCompare(b.feature)), gaps };
}

export function render(row) {
  const theme = row.shape === 'theme-color';
  const entry = theme ? `Press Ctrl+K, run Themes, type \`${row.query}\`, and press Enter.`
    : row.shape === 'sidebar-cycle' ? `Press ${row.chord} three times, once per state.`
      : 'Press Ctrl+K and run Sidebar: expand after hiding the sidebar with Ctrl+Shift+B.';
  const assertion = theme ? `Require the app-written theme-mode.txt to equal \`${row.saved}\`. Require the dominant sidebar RGB channels to equal ${row.rgb}, within 4 shades.`
    : 'Require the saved sidebar flags at each step and the actual console HWND left edge to move as the sidebar collapses, hides, and expands. Require the restored edge to match its baseline.';
  return `# ${row.title}\n\nGenerated by \`node tools/generate-feature-journeys.mjs\`. Do not edit this file.\n\nCovers: ${row.id}\n\nSource files: src/main.zig, src/shortcuts.zig, src/command_palette.zig, ${theme ? 'src/themes.zig' : 'src/session.zig'}, tools/generate-feature-journeys.mjs, ${skill}/generated-journeys.json, ${skill}/control-feature-generated.ps1, ${skill}/control.ps1${row.shape === 'sidebar-cycle' ? ', tools/plant-shortcut-break.mjs' : ''}\n\nVerify on: push, pull_request\n\n## Sub-features\n\n- One source row, checked by the shared \`${row.shape}\` assertion.\n\n## How to get to it\n\n${entry}\n\n## Driving it with control.ps1\n\nRun \`gh workflow run verify.yml -f feature=${row.feature}\` on GitHub Windows. The workflow opens an isolated real app through \`drive.ps1\`; Doctor checks its identity before input. ${entry}\n\n${theme ? 'First select a contrasting theme through the UI. Select this row through the real Themes palette and close it with Escape.' : 'Use palette expansion as the initial open state. Select the owned CMD tab. Read native console geometry before and after real keyboard input.'}\n\n${assertion} Inspect \`result.json\`, the saved data, and before/action/after screenshots. Each input and assertion is retained; a missing state fails rather than skips. Require zero owned processes and scratch removal after cleanup.\n\n## Gotchas\n\nThis row does not cover other palette entries or shortcut alternatives. Offline sign-in is explicit; account sync and remote agents are not exercised. Run \`node tools/generate-feature-journeys.mjs --gaps\` for source entries without a generated assertion.\n`;
}

export function outputs(read) {
  const { rows, gaps } = generate(read);
  const files = new Map(rows.map(row => [`${featureDirectory}/${row.feature}.md`, render(row)]));
  files.set(manifest, JSON.stringify(rows, null, 2) + '\n');
  const index = `${featureDirectory}/README.md`;
  const block = `<!-- GENERATED-JOURNEYS:START -->\n${rows.map(row => `- [${row.title}](${row.feature}.md).`).join('\n')}\n<!-- GENERATED-JOURNEYS:END -->`;
  const previous = read(index);
  files.set(index, previous.includes('<!-- GENERATED-JOURNEYS:START -->')
    ? previous.replace(/<!-- GENERATED-JOURNEYS:START -->[^]*?<!-- GENERATED-JOURNEYS:END -->/, () => block)
    : `${previous.trimEnd()}\n\n## Generated source-row journeys\n\n${block}\n`);
  const control = `${skill}/control.ps1`;
  files.set(control, read(control).replace(/ValidateSet\(([^\n)]+)\)/, (_, names) => {
    const existing = [...names.matchAll(/'([^']+)'/g)].map(match => match[1]).filter(name => !name.startsWith('generated-'));
    return `ValidateSet(${[...existing, ...rows.map(row => row.feature)].map(name => `'${name}'`).join(', ')})`;
  }));
  return { files, rows, gaps };
}

export function main(args, directory = root) {
  if (args.some(arg => !['--check', '--gaps'].includes(arg))) throw new Error('Usage: node tools/generate-feature-journeys.mjs [--check] [--gaps]');
  const read = file => fs.readFileSync(path.join(directory, file), 'utf8');
  const { files, rows, gaps } = outputs(read);
  const stale = fs.readdirSync(path.join(directory, featureDirectory)).filter(file => file.startsWith('generated-') && file.endsWith('.md') && !files.has(`${featureDirectory}/${file}`));
  const changed = [...files].filter(([file, text]) => !fs.existsSync(path.join(directory, file)) || read(file) !== text);
  if (args.includes('--check')) {
    if (changed.length || stale.length) throw new Error('Generated journeys are stale; run node tools/generate-feature-journeys.mjs');
  } else {
    for (const [file, text] of changed) fs.writeFileSync(path.join(directory, file), text);
    for (const file of stale) fs.unlinkSync(path.join(directory, featureDirectory, file));
  }
  console.log(`Generated live row recipes: ${rows.length}. Entries needing another assertion: ${gaps.length}. Existing independent coverage is counted by check-feature-coverage.mjs.`);
  if (args.includes('--gaps')) for (const gap of gaps) console.log(`${gap.id} | ${gap.reason}`);
  return { rows, gaps };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
